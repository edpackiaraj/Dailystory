const taPath = 'data/ta/stories-ta.json';
const taStories = JSON.parse(fs.readFileSync(taPath, 'utf8'));

for (const story of stories) {
  const idx = taStories.findIndex(s => s.id === story.id);
  if (idx !== -1) {
    taStories[idx] = { ...taStories[idx], ...story };
  } else {
    console.warn(`Story ${story.id} not found in stories-ta.json!`);
  }
}

fs.writeFileSync(taPath, JSON.stringify(taStories, null, 2), 'utf8');
