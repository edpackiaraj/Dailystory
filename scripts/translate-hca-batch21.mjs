let errors = 0;
const expectedTiers = ['remembering', 'understanding', 'applying', 'analyzing', 'evaluating', 'creating'];

for (const story of stories) {
  if (!story.id || !story.title || !story.summary || !story.moral || !story.full_text) {
    console.error(`Missing base fields in ${story.id}`);
    errors++;
  }
  if (!Array.isArray(story.vocabulary) || story.vocabulary.length !== 4) {
    console.error(`Vocab length != 4 in ${story.id}`);
    errors++;
  } else {
    for (const v of story.vocabulary) {
      if (!v.word || !v.meaning || !v.gloss) {
        console.error(`Incomplete vocab in ${story.id}: ${JSON.stringify(v)}`);
        errors++;
      }
      if (!story.full_text.includes(v.word)) {
        console.error(`Vocab word '${v.word}' not found in full_text of ${story.id}`);
        errors++;
      }
    }
  }

  if (!Array.isArray(story.quiz) || story.quiz.length !== 3) {
    console.error(`Quiz length != 3 in ${story.id}`);
    errors++;
  } else {
    story.quiz.forEach((q, idx) => {
      if (!q.question || !Array.isArray(q.options) || q.options.length !== 4 || q.answerIndex === undefined || !q.answer || !q.hint || !q.explanation) {
        console.error(`Incomplete quiz ${idx} in ${story.id}`);
        errors++;
      }
      if (q.options[q.answerIndex] !== q.answer) {
        console.error(`Quiz answer mismatch in ${story.id} q${idx}: options[${q.answerIndex}] !== answer`);
        errors++;
      }
    });
  }

  if (!Array.isArray(story.discussion_questions) || story.discussion_questions.length !== 6) {
    console.error(`DQ length != 6 in ${story.id}`);
    errors++;
  } else {
    story.discussion_questions.forEach((dq, idx) => {
      if (dq.tier !== expectedTiers[idx] || dq.type !== expectedTiers[idx]) {
        console.error(`DQ tier mismatch at ${idx} in ${story.id}: ${dq.tier} / ${dq.type}`);
        errors++;
      }
      if (!dq.prompt || !dq.question || dq.prompt !== dq.question) {
        console.error(`DQ prompt !== question at ${idx} in ${story.id}`);
        errors++;
      }
    });
  }
}

if (errors > 0) {
  console.error(`Self-validation failed with ${errors} errors! Aborting update.`);
  process.exit(1);
}

console.log("Self-validation passed with 0 errors.");

