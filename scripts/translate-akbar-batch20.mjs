// Validation & Execution
const requiredTiers = [
  "Remembering",
  "Understanding",
  "Applying",
  "Analyzing",
  "Evaluating",
  "Creating"
];

for (const s of stories) {
  if (!s.full_text || s.full_text.length < 200) {
    console.error(`ERROR in ${s.id}: full_text too short!`);
    process.exit(1);
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`ERROR in ${s.id}: vocabulary count is not 4!`);
    process.exit(1);
  }
  for (const v of s.vocabulary) {
    if (!s.full_text.includes(v.word)) {
      console.error(`ERROR in ${s.id}: vocabulary word "${v.word}" NOT found in full_text!`);
      process.exit(1);
    }
  }
  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`ERROR in ${s.id}: quiz count is not 3!`);
    process.exit(1);
  }
  for (const q of s.quiz) {
    if (q.options.length !== 4) {
      console.error(`ERROR in ${s.id}: quiz options count is not 4!`);
      process.exit(1);
    }
    if (q.options[q.answerIndex] !== q.answer) {
      console.error(`ERROR in ${s.id}: quiz answer mismatch!`);
      process.exit(1);
    }
  }
  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`ERROR in ${s.id}: discussion_questions count is not 6!`);
    process.exit(1);
  }
  const tiers = s.discussion_questions.map(dq => dq.tier);
  for (let i = 0; i < 6; i++) {
    if (tiers[i] !== requiredTiers[i]) {
      console.error(`ERROR in ${s.id}: tier #${i} is "${tiers[i]}", expected "${requiredTiers[i]}"!`);
      process.exit(1);
    }
  }
}

