// Self-validation
console.log('Self-validating Aesop Batch 09 (Stories 115-120)...');
let errors = 0;
const bloomOrder = ['remembering', 'understanding', 'applying', 'analyzing', 'evaluating', 'creating'];

for (const s of stories) {
  if (!s.id || !s.title || !s.summary || !s.moral || !s.full_text) {
    console.error(`Missing basic field in ${s.id}`);
    errors++;
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`Vocab count !== 4 in ${s.id}`);
    errors++;
  } else {
    for (const v of s.vocabulary) {
      if (!s.full_text.includes(v.word)) {
        console.error(`Vocab word '${v.word}' not found in full_text of ${s.id}`);
        errors++;
      }
      if (!v.meaning || !v.gloss) {
        console.error(`Missing meaning/gloss for '${v.word}' in ${s.id}`);
        errors++;
      }
    }
  }

  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`Quiz count !== 3 in ${s.id}`);
    errors++;
  } else {
    for (const q of s.quiz) {
      if (!q.options || q.options.length !== 4) {
        console.error(`Quiz options !== 4 in ${s.id}: ${q.question}`);
        errors++;
      }
      if (!q.options.includes(q.answer)) {
        console.error(`Quiz answer not in options in ${s.id}: ${q.question}`);
        errors++;
      }
      if (!q.hint || !q.explanation) {
        console.error(`Missing quiz hint/explanation in ${s.id}: ${q.question}`);
        errors++;
      }
    }
  }

  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`Discussion questions count !== 6 in ${s.id}`);
    errors++;
  } else {
    for (let i = 0; i < 6; i++) {
      const dq = s.discussion_questions[i];
      const expectedTier = bloomOrder[i];
      if (dq.tier !== expectedTier || dq.type !== expectedTier) {
        console.error(`DQ tier mismatch at [${i}] in ${s.id}: got ${dq.tier}/${dq.type}, expected ${expectedTier}`);
        errors++;
      }
      if (!dq.prompt || dq.prompt !== dq.question) {
        console.error(`DQ prompt/question mismatch in ${s.id} at [${i}]`);
        errors++;
      }
    }
  }
}

if (errors > 0) {
  console.error(`Self-validation failed with ${errors} errors! Aborting update.`);
  process.exit(1);
}

console.log('Self-validation passed with 0 errors.');

