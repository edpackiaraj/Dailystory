const enStories = JSON.parse(fs.readFileSync('data/en/stories-en.json', 'utf8'));

for (const s of stories) {
  const idx = taStories.findIndex(x => x.id === s.id);
  if (idx === -1) {
    console.error(`Story ID not found in stories-ta: ${s.id}`);
    process.exit(1);
  }

  const en = enStories[idx];
  const wordCount = s.full_text.trim().split(/\s+/).length;
  const readingTime = Math.max(1, Math.ceil(wordCount / 150));

  taStories[idx] = {
    ...en,
    ...s,
    language: 'ta',
    word_count: wordCount,
    reading_time: readingTime
  };
  console.log(`Updated existing story: ${s.id} at index ${idx}`);
}

fs.writeFileSync('data/ta/stories-ta.json', JSON.stringify(taStories, null, 2), 'utf8');
console.log('Successfully written to data/ta/stories-ta.json');
