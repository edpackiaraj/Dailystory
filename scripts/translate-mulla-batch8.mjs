for (const item of batch) {
  const index = stories.findIndex(s => s.id === item.id);
  if (index !== -1) {
    stories[index] = {
      ...stories[index],
      ...item
    };
    updated++;
  } else {
    console.warn(`Story not found: ${item.id}`);
  }
}

fs.writeFileSync(storiesPath, JSON.stringify(stories, null, 2), 'utf8');
console.log(`Successfully updated ${updated} stories in ${storiesPath}!`);
