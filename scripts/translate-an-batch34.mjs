// Self-validation
for (const story of batchData) {
  if (!story.title || !story.summary || !story.moral || !story.full_text) {
    throw new Error(`Incomplete basic fields in ${story.id}`);
  }
  if (story.vocabulary.length !== 4) {
    throw new Error(`Story ${story.id} must have exactly 4 vocabulary items`);
  }
  for (const v of story.vocabulary) {
    if (!story.full_text.includes(v.word)) {
      throw new Error(`Vocab word "${v.word}" not found verbatim in full_text of ${story.id}`);
    }
  }
  if (story.quiz.length !== 3) {
    throw new Error(`Story ${story.id} must have exactly 3 quiz questions`);
  }
  for (const q of story.quiz) {
    if (q.options.length !== 4) {
      throw new Error(`Quiz question in ${story.id} does not have 4 options`);
    }
    if (q.options[q.answerIndex] !== q.answer) {
      throw new Error(`Quiz answer mismatch in ${story.id}: options[${q.answerIndex}] !== answer`);
    }
    if (!q.hint || !q.explanation) {
      throw new Error(`Quiz question in ${story.id} missing hint or explanation`);
    }
  }
  if (story.discussion_questions.length !== 6) {
    throw new Error(`Story ${story.id} must have exactly 6 discussion questions`);
  }
  const expectedTiers = ["remembering", "understanding", "applying", "analyzing", "evaluating", "creating"];
  for (let i = 0; i < 6; i++) {
    const dq = story.discussion_questions[i];
    if (dq.tier !== expectedTiers[i] || dq.type !== expectedTiers[i]) {
      throw new Error(`Discussion question ${i} in ${story.id} tier mismatch: expected ${expectedTiers[i]}`);
    }
    if (!dq.prompt || !dq.question || dq.prompt !== dq.question) {
      throw new Error(`Discussion question ${i} in ${story.id} prompt/question mismatch or empty`);
    }
  }
}

console.log(`All ${batchData.length} Arabian Nights stories in Batch 34 passed self-validation!`);

// Load existing stories
const raw = fs.readFileSync(STORIES_PATH, 'utf8');
const stories = JSON.parse(raw);

let updatedCount = 0;
for (const bStory of batchData) {
  const idx = stories.findIndex(s => s.id === bStory.id);
  if (idx !== -1) {
    stories[idx] = {
      ...stories[idx],
      ...bStory
    };
    updatedCount++;
  } else {
    throw new Error(`Story ID ${bStory.id} not found in stories-ta.json`);
  }
}

// Write with retry logic for OneDrive lock handling
let written = false;
for (let attempt = 1; attempt <= 5; attempt++) {
  try {
    fs.writeFileSync(STORIES_PATH, JSON.stringify(stories, null, 2), 'utf8');
    written = true;
    break;
  } catch (err) {
    console.log(`Attempt ${attempt} failed to write stories-ta.json: ${err.message}. Retrying in 1s...`);
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000);
  }
}

if (!written) {
  throw new Error("Failed to write to stories-ta.json after 5 attempts");
}

console.log(`Successfully updated ${updatedCount} stories in data/ta/stories-ta.json!`);
