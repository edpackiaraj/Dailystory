// Verbatim vocabulary check
for (const s of storiesData) {
  for (const v of s.vocabulary) {
    if (!s.full_text.includes(v.word)) {
      console.error(`ERROR in ${s.id}: vocabulary word "${v.word}" NOT found in full_text!`);
      process.exit(1);
    }
  }
  if (s.vocabulary.length !== 4) throw new Error(`${s.id} vocabulary length != 4`);
  if (s.quiz.length !== 3) throw new Error(`${s.id} quiz length != 3`);
  if (s.discussion_questions.length !== 6) throw new Error(`${s.id} discussion length != 6`);
}
console.log('All 6 Tenali Rama stories in Batch 13 passed self-validation with 6-stage Bloom taxonomy!');

// Load master data/ta/stories-ta.json
const taPath = 'data/ta/stories-ta.json';
const ta = JSON.parse(fs.readFileSync(taPath, 'utf8'));

let updated = 0;
for (const s of storiesData) {
  const idx = ta.findIndex(x => x.id === s.id);
  if (idx !== -1) {
    // Enrich quiz with answerIndex and hint
    const enrichedQuiz = s.quiz.map(q => {
      const idx = q.options.indexOf(q.answer);
      return {
        ...q,
        answerIndex: idx !== -1 ? idx : 0,
        hint: q.explanation
      };
    });

    ta[idx] = {
      ...ta[idx],
      title: s.title,
      summary: s.summary,
      moral: s.moral,
      full_text: s.full_text,
      vocabulary: s.vocabulary,
      quiz: enrichedQuiz,
      discussion_questions: s.discussion_questions
    };
    updated++;
  } else {
    console.error(`Story ID not found in ta: ${s.id}`);
  }
}

fs.writeFileSync(taPath, JSON.stringify(ta, null, 2), 'utf8');
console.log(`Successfully updated ${updated} stories in ${taPath}!`);
