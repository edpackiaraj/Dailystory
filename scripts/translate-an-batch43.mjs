// Self-validation
for (const story of batchData) {
  if (!story.title || !story.summary || !story.moral || !story.full_text) {
    throw new Error(`Incomplete basic fields in ${story.id}`);
  }
  if (story.vocabulary.length !== 4) {
    throw new Error(`Expected exactly 4 vocab words in ${story.id}, got ${story.vocabulary.length}`);
  }
  for (const v of story.vocabulary) {
    if (!v.word || !v.meaning || !v.gloss) {
      throw new Error(`Incomplete vocab item in ${story.id}: ${JSON.stringify(v)}`);
    }
    if (!story.full_text.includes(v.word)) {
      throw new Error(`Vocab word "${v.word}" not found verbatim in full_text of ${story.id}`);
    }
  }
  if (story.quiz.length !== 3) {
    throw new Error(`Expected exactly 3 quiz questions in ${story.id}, got ${story.quiz.length}`);
  }
  for (const q of story.quiz) {
    if (!q.question || !Array.isArray(q.options) || q.options.length !== 4 || !q.answer || q.answerIndex === undefined || !q.hint || !q.explanation) {
      throw new Error(`Incomplete quiz question in ${story.id}: ${JSON.stringify(q)}`);
    }
    if (q.options[q.answerIndex] !== q.answer) {
      throw new Error(`Quiz answerIndex mismatch in ${story.id}: ${q.answer} !== ${q.options[q.answerIndex]}`);
    }
  }
  if (story.discussion_questions.length !== 6) {
    throw new Error(`Expected exactly 6 discussion questions in ${story.id}, got ${story.discussion_questions.length}`);
  }
  const tiers = ["remembering", "understanding", "applying", "analyzing", "evaluating", "creating"];
  story.discussion_questions.forEach((dq, idx) => {
    if (dq.tier !== tiers[idx] || dq.type !== tiers[idx]) {
      throw new Error(`Invalid tier sequence in ${story.id} at index ${idx}: expected ${tiers[idx]}, got ${dq.tier}/${dq.type}`);
    }
    if (!dq.prompt || !dq.question || dq.prompt !== dq.question) {
      throw new Error(`Dual prompt/question mismatch in ${story.id} at index ${idx}`);
    }
  });
}

