const filePath = 'data/ta/stories-ta.json';
const ta = JSON.parse(fs.readFileSync(filePath, 'utf8'));

let updated = 0;
for (const s of stories) {
  const idx = ta.findIndex(item => item.id === s.id);
  if (idx !== -1) {
    ta[idx].title = s.title;
    ta[idx].summary = s.summary;
    ta[idx].moral = s.moral;
    ta[idx].full_text = s.full_text;
    ta[idx].vocabulary = s.vocabulary;
    ta[idx].quiz = s.quiz;
    ta[idx].discussion_questions = s.discussion_questions;
    updated++;
  } else {
    console.error(`Story ID not found in data/ta/stories-ta.json: ${s.id}`);
    process.exit(1);
  }
}

fs.writeFileSync(filePath, JSON.stringify(ta, null, 2), 'utf8');
console.log(`Successfully updated ${updated} stories in data/ta/stories-ta.json!`);
