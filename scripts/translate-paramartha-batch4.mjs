let updatedCount = 0;
for (const item of batch) {
  const index = stories.findIndex(s => s.id === item.id);
  if (index !== -1) {
    stories[index] = {
      ...stories[index],
      title: item.title,
      summary: item.summary,
      moral: item.moral,
      full_text: item.full_text,
      vocabulary: item.vocabulary,
      quiz: item.quiz,
      discussion_questions: item.discussion_questions,
      language: "ta",
      is_translated: true
    };
    updatedCount++;
  } else {
    console.warn(`Story not found in stories-ta.json: ${item.id}`);
  }
}

