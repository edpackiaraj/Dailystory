function selfValidate(batch) {
  const bloomTiers = ["remembering", "understanding", "applying", "analyzing", "evaluating", "creating"];
  let errors = 0;

  for (const story of batch) {
    if (!story.id || !story.title || !story.summary || !story.moral || !story.full_text) {
      console.error(`Missing primary field in ${story.id}`);
      errors++;
    }
    if (!story.vocabulary || story.vocabulary.length !== 4) {
      console.error(`Vocab length != 4 in ${story.id}`);
      errors++;
    } else {
      for (const v of story.vocabulary) {
        if (!v.word || !v.meaning || !v.gloss) {
          console.error(`Incomplete vocab in ${story.id}: ${JSON.stringify(v)}`);
          errors++;
        }
        if (!story.full_text.includes(v.word)) {
          console.error(`Vocab word '${v.word}' not found in full_text of ${story.id}`);
          errors++;
        }
      }
    }
    if (!story.quiz || story.quiz.length !== 3) {
      console.error(`Quiz length != 3 in ${story.id}`);
      errors++;
    } else {
      for (const q of story.quiz) {
        if (!q.question || !Array.isArray(q.options) || q.options.length !== 4 || q.answerIndex === undefined || !q.answer || !q.hint || !q.explanation) {
          console.error(`Incomplete quiz in ${story.id}: ${JSON.stringify(q)}`);
          errors++;
        }
        if (q.options[q.answerIndex] !== q.answer) {
          console.error(`Quiz answer mismatch in ${story.id}: options[${q.answerIndex}] !== answer`);
          errors++;
        }
      }
    }
    if (!story.discussion_questions || story.discussion_questions.length !== 6) {
      console.error(`Discussion questions length != 6 in ${story.id}`);
      errors++;
    } else {
      for (let i = 0; i < 6; i++) {
        const dq = story.discussion_questions[i];
        const expectedTier = bloomTiers[i];
        if (dq.tier !== expectedTier || dq.type !== expectedTier) {
          console.error(`Bloom tier mismatch at ${i} in ${story.id}: got ${dq.tier}/${dq.type}, expected ${expectedTier}`);
          errors++;
        }
        if (!dq.prompt || !dq.question || dq.prompt !== dq.question) {
          console.error(`Prompt/question mismatch in ${story.id}: ${JSON.stringify(dq)}`);
          errors++;
        }
      }
    }
  }
  return errors;
}

