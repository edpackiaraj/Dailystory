// Validation
const requiredBloomTiers = ["Remembering", "Understanding", "Applying", "Analyzing", "Evaluating", "Creating"];

for (const story of stories) {
  if (!story.title || !story.summary || !story.moral || !story.full_text) {
    console.error(`ERROR in ${story.id}: Missing basic fields!`);
    process.exit(1);
  }
  if (!story.vocabulary || story.vocabulary.length !== 4) {
    console.error(`ERROR in ${story.id}: Vocabulary must have exactly 4 items, found ${story.vocabulary?.length}`);
    process.exit(1);
  }
  for (const v of story.vocabulary) {
    if (!story.full_text.includes(v.word)) {
      console.error(`ERROR in ${story.id}: vocabulary word "${v.word}" NOT found in full_text!`);
      process.exit(1);
    }
  }
  if (!story.quiz || story.quiz.length !== 3) {
    console.error(`ERROR in ${story.id}: Quiz must have exactly 3 items!`);
    process.exit(1);
  }
  for (let i = 0; i < story.quiz.length; i++) {
    const q = story.quiz[i];
    if (!q.options || q.options.length !== 4) {
      console.error(`ERROR in ${story.id} quiz #${i + 1}: Must have exactly 4 options!`);
      process.exit(1);
    }
    const idx = q.options.indexOf(q.answer);
    if (idx === -1) {
      console.error(`ERROR in ${story.id} quiz #${i + 1}: Answer "${q.answer}" not in options!`);
      process.exit(1);
    }
    q.answerIndex = idx;
    if (!q.explanation) {
      console.error(`ERROR in ${story.id} quiz #${i + 1}: Missing explanation!`);
      process.exit(1);
    }
  }
  if (!story.discussion_questions || story.discussion_questions.length !== 6) {
    console.error(`ERROR in ${story.id}: discussion_questions must have exactly 6 items!`);
    process.exit(1);
  }
  for (let i = 0; i < 6; i++) {
    const dq = story.discussion_questions[i];
    const expectedTier = requiredBloomTiers[i];
    if (dq.tier !== expectedTier) {
      console.error(`ERROR in ${story.id} DQ #${i + 1}: Expected tier ${expectedTier}, got ${dq.tier}`);
      process.exit(1);
    }
    if (!dq.prompt || !dq.question || dq.prompt !== dq.question) {
      console.error(`ERROR in ${story.id} DQ #${i + 1}: Prompt and question must be identical and non-empty!`);
      process.exit(1);
    }
  }
}

console.log("All 6 Akbar-Birbal stories in Batch 13 passed self-validation with 6-stage Bloom taxonomy!");

