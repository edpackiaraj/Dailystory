const stories = JSON.parse(raw);

let updatedCount = 0;
for (const bStory of batchData) {
  const idx = stories.findIndex(s => s.id === bStory.id);
  if (idx !== -1) {
    stories[idx] = {
      ...stories[idx],
      ...bStory
    };
    updatedCount++;
  } else {
    throw new Error(`Story ID ${bStory.id} not found in stories-ta.json`);
  }
}

// Write with retry logic for OneDrive lock handling
let written = false;
for (let attempt = 1; attempt <= 5; attempt++) {
  try {
    fs.writeFileSync(STORIES_PATH, JSON.stringify(stories, null, 2), 'utf8');
    written = true;
    break;
  } catch (err) {
    console.log(`Attempt ${attempt} failed to write stories-ta.json: ${err.message}. Retrying in 1s...`);
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000);
  }
}

if (!written) {
  throw new Error("Failed to write to stories-ta.json after 5 attempts");
}

console.log(`Successfully updated ${updatedCount} stories in data/ta/stories-ta.json!`);
