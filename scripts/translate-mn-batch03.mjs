// Self-validation
console.log("Self-validating Batch 03 (Mulla Nasruddin 113-118)...");
let errors = 0;
for (const s of batch03) {
  if (!s.title || !s.summary || !s.moral || !s.full_text) {
    console.error(`Missing basic field in ${s.id}`);
    errors++;
  }
  if (!Array.isArray(s.vocabulary) || s.vocabulary.length !== 4) {
    console.error(`Vocab length !== 4 in ${s.id}`);
    errors++;
  } else {
    for (const v of s.vocabulary) {
      if (!s.full_text.includes(v.word)) {
        console.error(`Vocab word '${v.word}' not found in full_text of ${s.id}`);
        errors++;
      }
    }
  }
  if (!Array.isArray(s.quiz) || s.quiz.length !== 3) {
    console.error(`Quiz length !== 3 in ${s.id}`);
    errors++;
  } else {
    for (const q of s.quiz) {
      if (q.options[q.answerIndex] !== q.answer) {
        console.error(`Quiz answer mismatch in ${s.id}: ${q.options[q.answerIndex]} !== ${q.answer}`);
        errors++;
      }
    }
  }
  const requiredTiers = ["remembering", "understanding", "applying", "analyzing", "evaluating", "creating"];
  if (!Array.isArray(s.discussion_questions) || s.discussion_questions.length !== 6) {
    console.error(`Discussion questions length !== 6 in ${s.id}`);
    errors++;
  } else {
    s.discussion_questions.forEach((dq, idx) => {
      if (dq.tier !== requiredTiers[idx] || dq.type !== requiredTiers[idx]) {
        console.error(`Tier mismatch at index ${idx} in ${s.id}: ${dq.tier} / ${dq.type}`);
        errors++;
      }
      if (dq.prompt !== dq.question) {
        console.error(`Dual prompt/question mismatch in ${s.id}`);
        errors++;
      }
    });
  }
}

if (errors > 0) {
  console.error(`Self-validation failed with ${errors} errors.`);
  process.exit(1);
}
console.log("Self-validation passed with 0 errors.");

