let updatedCount = 0;
for (const updated of batch17Data) {
  const idx = stories.findIndex(s => s.id === updated.id);
  if (idx !== -1) {
    stories[idx] = {
      ...stories[idx],
      ...updated,
      language: 'ta'
    };
    updatedCount++;
  } else {
    console.warn(`Story not found: ${updated.id}`);
  }
}

