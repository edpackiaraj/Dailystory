// Self-validation
let hasError = false;
for (const s of storiesData) {
  if (!s.title || !s.summary || !s.moral) {
    console.error(`ERROR in ${s.id}: missing title, summary or moral`);
    hasError = true;
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`ERROR in ${s.id}: vocabulary must have exactly 4 items`);
    hasError = true;
  }
  for (const v of s.vocabulary || []) {
    if (!s.full_text.includes(v.word)) {
      console.error(`ERROR in ${s.id}: vocabulary word "${v.word}" NOT found in full_text!`);
      hasError = true;
    }
  }
  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`ERROR in ${s.id}: quiz must have exactly 3 questions`);
    hasError = true;
  }
  for (const q of s.quiz || []) {
    if (!q.options || q.options.length !== 4) {
      console.error(`ERROR in ${s.id}: quiz question must have 4 options`);
      hasError = true;
    }
    const idx = q.options.indexOf(q.answer);
    if (idx === -1) {
      console.error(`ERROR in ${s.id}: answer "${q.answer}" not in options!`);
      hasError = true;
    }
    q.answerIndex = idx;
    if (!q.hint) q.hint = q.explanation;
  }
  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`ERROR in ${s.id}: discussion_questions must have exactly 6 Bloom questions`);
    hasError = true;
  }
}

if (hasError) {
  process.exit(1);
}

