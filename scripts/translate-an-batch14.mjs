// Validation
for (const story of batchData) {
  if (story.vocabulary.length !== 4) {
    throw new Error(`Story ${story.id} must have exactly 4 vocabulary items`);
  }
  for (const v of story.vocabulary) {
    if (!story.full_text.includes(v.word)) {
      throw new Error(`Vocabulary word "${v.word}" not found in full_text of ${story.id}`);
    }
  }
  if (story.quiz.length !== 3) {
    throw new Error(`Story ${story.id} must have exactly 3 quiz questions`);
  }
  for (const q of story.quiz) {
    if (q.options[q.answerIndex] !== q.answer) {
      throw new Error(`Quiz answer mismatch in ${story.id}: index ${q.answerIndex} vs ${q.answer}`);
    }
  }
  if (story.discussion_questions.length !== 6) {
    throw new Error(`Story ${story.id} must have exactly 6 discussion questions`);
  }
}

console.log('All 6 Arabian Nights stories in Batch 14 passed self-validation!');

// Apply updates with retry for OneDrive
let updatedCount = 0;
for (const updated of batchData) {
  const idx = stories.findIndex(s => s.id === updated.id);
  if (idx !== -1) {
    stories[idx] = {
      ...stories[idx],
      ...updated,
      language: 'ta'
    };
    updatedCount++;
  } else {
    console.warn(`Story not found: ${updated.id}`);
  }
}

let written = false;
for (let attempt = 1; attempt <= 5; attempt++) {
  try {
    fs.writeFileSync(STORIES_PATH, JSON.stringify(stories, null, 2), 'utf8');
    written = true;
    break;
  } catch (err) {
    console.log(`Attempt ${attempt} failed, waiting 1s...`);
    const end = Date.now() + 1000;
    while (Date.now() < end) {}
  }
}

if (!written) {
  throw new Error('Failed to write stories-ta.json after 5 attempts');
}

console.log(`Successfully updated ${updatedCount} stories in data/ta/stories-ta.json!`);
