for (const [id, update] of Object.entries(translations)) {
  const index = data.findIndex(s => s.id === id);
  if (index !== -1) {
    const existing = data[index];
    data[index] = {
      ...existing,
      title: update.title,
      summary: update.summary,
      full_text: update.full_text,
      moral: update.moral,
      vocabulary: update.vocabulary,
      quiz: update.quiz,
      discussion_questions: update.discussion_questions,
      word_count: update.full_text.split(/\s+/).filter(Boolean).length,
      reading_time: Math.ceil(update.full_text.split(/\s+/).filter(Boolean).length / 70),
      status: 'published'
    };
    console.log(`Updated [${id}]: ${update.title} (${data[index].word_count} words)`);
    count++;
  } else {
    console.warn(`Story not found: ${id}`);
  }
}

