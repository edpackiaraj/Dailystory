// Self-validation
for (const story of batchData) {
  if (!story.title || !story.summary || !story.moral || !story.full_text) {
    throw new Error(`Incomplete basic fields in ${story.id}`);
  }
  if (story.vocabulary.length !== 4) {
    throw new Error(`Story ${story.id} must have exactly 4 vocabulary items`);
  }
  for (const v of story.vocabulary) {
    if (!story.full_text.includes(v.word)) {
      throw new Error(`Vocab word "${v.word}" not found verbatim in full_text of ${story.id}`);
    }
  }
  if (story.quiz.length !== 3) {
    throw new Error(`Story ${story.id} must have exactly 3 quiz questions`);
  }
  for (const q of story.quiz) {
    if (q.options.length !== 4) {
      throw new Error(`Quiz question in ${story.id} does not have 4 options`);
    }
    if (q.options[q.answerIndex] !== q.answer) {
      throw new Error(`Quiz answer mismatch in ${story.id}: index ${q.answerIndex} vs ${q.answer}`);
    }
  }
  if (story.discussion_questions.length !== 6) {
    throw new Error(`Story ${story.id} must have exactly 6 discussion questions`);
  }
}

