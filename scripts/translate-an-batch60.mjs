// Self-validation
console.log('Self-validating Batch 60 stories...');
let errors = 0;
const expectedTiers = ["remembering", "understanding", "applying", "analyzing", "evaluating", "creating"];

batch60.forEach((story, idx) => {
  const storyNum = 379 + idx;
  if (!story.title || !story.summary || !story.moral || !story.full_text) {
    console.error(`Story ${storyNum} (${story.id}) missing basic fields!`);
    errors++;
  }
  if (!story.vocabulary || story.vocabulary.length !== 4) {
    console.error(`Story ${storyNum} (${story.id}) has ${story.vocabulary?.length} vocabulary items, expected 4!`);
    errors++;
  } else {
    story.vocabulary.forEach((v, vIdx) => {
      if (!v.word || !v.meaning || !v.gloss) {
        console.error(`Story ${storyNum} vocab ${vIdx} missing fields!`);
        errors++;
      }
      if (!story.full_text.includes(v.word)) {
        console.error(`Story ${storyNum} vocab word "${v.word}" not found verbatim in full_text!`);
        errors++;
      }
    });
  }

  if (!story.quiz || story.quiz.length !== 3) {
    console.error(`Story ${storyNum} (${story.id}) has ${story.quiz?.length} quizzes, expected 3!`);
    errors++;
  } else {
    story.quiz.forEach((q, qIdx) => {
      if (!q.question || !q.options || q.options.length !== 4 || q.answerIndex === undefined || !q.answer || !q.hint || !q.explanation) {
        console.error(`Story ${storyNum} quiz ${qIdx} missing fields!`);
        errors++;
      }
      if (q.options[q.answerIndex] !== q.answer) {
        console.error(`Story ${storyNum} quiz ${qIdx} options[${q.answerIndex}] ("${q.options[q.answerIndex]}") !== answer ("${q.answer}")!`);
        errors++;
      }
    });
  }

  if (!story.discussion_questions || story.discussion_questions.length !== 6) {
    console.error(`Story ${storyNum} (${story.id}) has ${story.discussion_questions?.length} discussion questions, expected 6!`);
    errors++;
  } else {
    story.discussion_questions.forEach((dq, dIdx) => {
      if (dq.tier !== expectedTiers[dIdx]) {
        console.error(`Story ${storyNum} dq ${dIdx} tier "${dq.tier}" !== expected "${expectedTiers[dIdx]}"!`);
        errors++;
      }
      if (dq.type !== dq.tier) {
        console.error(`Story ${storyNum} dq ${dIdx} type "${dq.type}" !== tier "${dq.tier}"!`);
        errors++;
      }
      if (dq.prompt !== dq.question) {
        console.error(`Story ${storyNum} dq ${dIdx} prompt !== question!`);
        errors++;
      }
    });
  }
});

if (errors > 0) {
  console.error(`Validation failed with ${errors} errors!`);
  process.exit(1);
}
console.log('Self-validation passed with 0 errors.');

