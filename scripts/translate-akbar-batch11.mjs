let updated = 0;
for (const s of storiesData) {
  const idx = ta.findIndex(x => x.id === s.id);
  if (idx !== -1) {
    // Enrich quiz with answerIndex and hint
    const enrichedQuiz = s.quiz.map(q => {
      const idx = q.options.indexOf(q.answer);
      return {
        ...q,
        answerIndex: idx !== -1 ? idx : 0,
        hint: q.explanation
      };
    });

    ta[idx] = {
      ...ta[idx],
      title: s.title,
      summary: s.summary,
      moral: s.moral,
      full_text: s.full_text,
      vocabulary: s.vocabulary,
      quiz: enrichedQuiz,
      discussion_questions: s.discussion_questions
    };
    updated++;
  } else {
    console.error(`Story ID not found in ta: ${s.id}`);
  }
}

fs.writeFileSync(taPath, JSON.stringify(ta, null, 2), 'utf8');
console.log(`Successfully updated ${updated} stories in ${taPath}!`);
