let written = false;
for (let attempt = 1; attempt <= 5; attempt++) {
  try {
    fs.writeFileSync(STORIES_PATH, JSON.stringify(stories, null, 2), 'utf8');
    written = true;
    break;
  } catch (err) {
    console.log(`Attempt ${attempt} failed to write stories-ta.json: ${err.message}. Retrying in 1s...`);
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000);
  }
}

if (!written) {
  throw new Error("Failed to write to stories-ta.json after 5 attempts");
}

