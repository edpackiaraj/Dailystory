console.log('Self-validating Vikram-Vetal Batch 02 (Stories 47-54)...');
let errors = 0;
for (const s of batch02Stories) {
  if (!s.full_text || s.full_text.length < 200) {
    console.error(`Full text too short for ${s.id}`);
    errors++;
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`Vocab count not 4 in ${s.id}`);
    errors++;
  } else {
    for (const v of s.vocabulary) {
      if (!s.full_text.includes(v.word)) {
        console.error(`Vocab word '${v.word}' not found in full_text of ${s.id}`);
        errors++;
      }
    }
  }
  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`Quiz count not 3 in ${s.id}`);
    errors++;
  } else {
    for (const q of s.quiz) {
      if (!q.options || q.options.length !== 4) {
        console.error(`Quiz options count not 4 in ${s.id}: ${q.question}`);
        errors++;
      }
      if (q.options[q.answerIndex] !== q.answer) {
        console.error(`Quiz answer mismatch in ${s.id}: answer '${q.answer}' !== options[${q.answerIndex}] '${q.options[q.answerIndex]}'`);
        errors++;
      }
    }
  }
  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`Discussion questions count not 6 in ${s.id}`);
    errors++;
  } else {
    const tiers = ['remembering', 'understanding', 'applying', 'analyzing', 'evaluating', 'creating'];
    s.discussion_questions.forEach((dq, i) => {
      if (dq.tier !== tiers[i] || dq.type !== tiers[i]) {
        console.error(`Discussion tier mismatch at index ${i} in ${s.id}`);
        errors++;
      }
      if (dq.prompt !== dq.question) {
        console.error(`Discussion prompt/question mismatch at index ${i} in ${s.id}`);
        errors++;
      }
    });
  }
}

if (errors > 0) {
  console.error(`Self-validation failed with ${errors} errors! Aborting update.`);
  process.exit(1);
}
console.log('Self-validation passed with 0 errors.');

