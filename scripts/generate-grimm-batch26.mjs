storiesData.forEach(item => {
  const targetIdx = allStories.findIndex(s => s.id === item.id);
  if (targetIdx === -1) {
    console.error(`Story with id ${item.id} not found in allStories!`);
    process.exit(1);
  }

  const existing = allStories[targetIdx];
  const words = item.full_text.trim().split(/\s+/).length;

  allStories[targetIdx] = {
    ...existing,
    title: item.title,
    summary: item.summary,
    moral: item.moral,
    full_text: item.full_text,
    word_count: words,
    vocabulary: item.vocabulary,
    quiz: item.quiz,
    discussion_questions: item.discussion_questions,
    language: 'ta'
  };
  console.log(`Updated story ${item.id} at index ${targetIdx} (${words} words)`);
});

