let errors = 0;
const expectedTiers = ["remembering", "understanding", "applying", "analyzing", "evaluating", "creating"];

for (const story of batch03) {
  if (!story.full_text || story.full_text.length < 200) {
    console.error(`Full text too short in ${story.id}`);
    errors++;
  }
  if (!story.vocabulary || story.vocabulary.length !== 4) {
    console.error(`Vocab count not 4 in ${story.id}`);
    errors++;
  } else {
    for (const v of story.vocabulary) {
      if (!story.full_text.includes(v.word)) {
        console.error(`Vocab word '${v.word}' not found in full_text of ${story.id}`);
        errors++;
      }
    }
  }
  if (!story.quiz || story.quiz.length !== 3) {
    console.error(`Quiz count not 3 in ${story.id}`);
    errors++;
  } else {
    for (const q of story.quiz) {
      if (q.options[q.answerIndex] !== q.answer) {
        console.error(`Quiz answer mismatch in ${story.id}: ${q.answer}`);
        errors++;
      }
    }
  }
  if (!story.discussion_questions || story.discussion_questions.length !== 6) {
    console.error(`Discussion count not 6 in ${story.id}`);
    errors++;
  } else {
    story.discussion_questions.forEach((dq, idx) => {
      if (dq.tier !== expectedTiers[idx] || dq.type !== expectedTiers[idx]) {
        console.error(`Discussion tier mismatch at ${idx} in ${story.id}: ${dq.tier}/${dq.type}`);
        errors++;
      }
      if (dq.prompt !== dq.question) {
        console.error(`Dual prompt/question mismatch in ${story.id}: ${dq.prompt} !== ${dq.question}`);
        errors++;
      }
    });
  }
}

if (errors > 0) {
  console.error(`Self-validation failed with ${errors} errors.`);
  process.exit(1);
}

console.log('Self-validation passed with 0 errors.');

// Apply updates
for (const item of batch03) {
  const idx = stories.findIndex(s => s.id === item.id);
  if (idx !== -1) {
    stories[idx].title = item.title;
    stories[idx].summary = item.summary;
    stories[idx].moral = item.moral;
    stories[idx].full_text = item.full_text;
    stories[idx].vocabulary = item.vocabulary;
    stories[idx].quiz = item.quiz;
    stories[idx].discussion_questions = item.discussion_questions;
    console.log(`Updated existing story: ${item.id} at index ${idx}`);
  } else {
    console.error(`Story ID not found: ${item.id}`);
    process.exit(1);
  }
}

