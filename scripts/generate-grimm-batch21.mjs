let validationErrors = 0;

storiesData.forEach((s, idx) => {
  const words = s.full_text.trim().split(/\s+/).length;
  console.log(`Story ${s.id}: ${words} words`);
  if (words < 160 || words > 185) {
    console.error(`[ERR] Story ${s.id} words out of range (160-185): ${words}`);
    validationErrors++;
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`[ERR] Story ${s.id} vocab count !== 4`);
    validationErrors++;
  } else {
    s.vocabulary.forEach((v, vIdx) => {
      if (!s.full_text.includes(v.word)) {
        console.error(`[ERR] Story ${s.id} vocab [${vIdx}] '${v.word}' not in full_text`);
        validationErrors++;
      }
      if (!v.gloss || v.gloss.trim() === '') {
        console.error(`[ERR] Story ${s.id} vocab [${vIdx}] missing gloss`);
        validationErrors++;
      }
    });
  }

  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`[ERR] Story ${s.id} quiz count !== 3`);
    validationErrors++;
  } else {
    s.quiz.forEach((q, qIdx) => {
      if (!q.options || q.options.length !== 4) {
        console.error(`[ERR] Story ${s.id} quiz [${qIdx}] options !== 4`);
        validationErrors++;
      }
      if (q.answerIndex < 0 || q.answerIndex > 3) {
        console.error(`[ERR] Story ${s.id} quiz [${qIdx}] invalid answerIndex`);
        validationErrors++;
      }
      if (!q.hint || !q.explanation) {
        console.error(`[ERR] Story ${s.id} quiz [${qIdx}] missing hint/explanation`);
        validationErrors++;
      }
    });
  }

  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`[ERR] Story ${s.id} dq count !== 6`);
    validationErrors++;
  } else {
    s.discussion_questions.forEach((dq, dIdx) => {
      if (dq.tier !== bloomTiers[dIdx] || dq.type !== bloomTiers[dIdx]) {
        console.error(`[ERR] Story ${s.id} dq [${dIdx}] tier/type mismatch: expected ${bloomTiers[dIdx]}`);
        validationErrors++;
      }
      if (!dq.prompt || dq.prompt !== dq.question) {
        console.error(`[ERR] Story ${s.id} dq [${dIdx}] prompt/question mismatch or empty`);
        validationErrors++;
      }
    });
  }
});

if (validationErrors > 0) {
  console.error(`\nValidation failed with ${validationErrors} errors.`);
  process.exit(1);
}
console.log('\nValidation passed for all 10 stories with 0 errors!\n');

