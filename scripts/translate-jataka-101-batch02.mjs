// Self-validation
console.log('Self-validating Jataka Batch 109-116...');
const BLOOM_TIERS = ['remembering', 'understanding', 'applying', 'analyzing', 'evaluating', 'creating'];
let errorCount = 0;

for (const story of batch02) {
  if (!story.title || !story.summary || !story.moral || !story.full_text) {
    console.error(`Story at index ${story.index} missing basic fields`);
    errorCount++;
  }
  if (!story.vocabulary || story.vocabulary.length !== 4) {
    console.error(`Story at index ${story.index} does not have exactly 4 vocab items`);
    errorCount++;
  } else {
    for (const v of story.vocabulary) {
      if (!v.word || !v.meaning || !v.gloss) {
        console.error(`Story at index ${story.index} vocab missing word/meaning/gloss:`, v);
        errorCount++;
      }
      if (!story.full_text.includes(v.word)) {
        console.error(`Story at index ${story.index} vocab word "${v.word}" not found verbatim in full_text`);
        errorCount++;
      }
    }
  }
  if (!story.quiz || story.quiz.length !== 3) {
    console.error(`Story at index ${story.index} does not have exactly 3 quiz questions`);
    errorCount++;
  } else {
    for (const q of story.quiz) {
      if (!q.question || !q.options || q.options.length !== 4 || typeof q.answerIndex !== 'number' || !q.hint || !q.explanation) {
        console.error(`Story at index ${story.index} quiz invalid:`, q);
        errorCount++;
      }
    }
  }
  if (!story.discussion_questions || story.discussion_questions.length !== 6) {
    console.error(`Story at index ${story.index} does not have exactly 6 DQs`);
    errorCount++;
  } else {
    story.discussion_questions.forEach((dq, idx) => {
      const expectedTier = BLOOM_TIERS[idx];
      if (dq.tier !== expectedTier || dq.type !== expectedTier) {
        console.error(`Story at index ${story.index} DQ ${idx} tier mismatch: expected ${expectedTier}, got tier=${dq.tier}, type=${dq.type}`);
        errorCount++;
      }
      if (!dq.prompt || !dq.question || dq.prompt !== dq.question) {
        console.error(`Story at index ${story.index} DQ ${idx} prompt/question mismatch:`, dq);
        errorCount++;
      }
    });
  }
}

if (errorCount > 0) {
  console.error(`Self-validation failed with ${errorCount} errors. Aborting write.`);
  process.exit(1);
}

console.log('Self-validation passed with 0 errors.');

// Apply updates
for (const update of batch02) {
  const target = stories[update.index];
  if (!target) {
    console.error(`Story at index ${update.index} not found in master!`);
    process.exit(1);
  }
  target.title = update.title;
  target.summary = update.summary;
  target.moral = update.moral;
  target.full_text = update.full_text;
  target.vocabulary = update.vocabulary;
  target.quiz = update.quiz;
  target.discussion_questions = update.discussion_questions;
  target.word_count = update.full_text.split(/\s+/).filter(Boolean).length;
  console.log(`Updated story: ${target.slug} at index ${update.index} (words: ${target.word_count})`);
}

