// Self-validation
let hasErrors = false;
for (const s of batch) {
  if (!s.full_text || s.full_text.length < 200) {
    console.error(`ERROR in ${s.id}: full_text too short or empty!`);
    hasErrors = true;
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`ERROR in ${s.id}: vocabulary must have exactly 4 items!`);
    hasErrors = true;
  } else {
    for (const v of s.vocabulary) {
      if (!s.full_text.includes(v.word)) {
        console.error(`ERROR in ${s.id}: vocabulary word "${v.word}" NOT found in full_text!`);
        hasErrors = true;
      }
    }
  }
  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`ERROR in ${s.id}: quiz must have exactly 3 items!`);
    hasErrors = true;
  } else {
    for (let i = 0; i < s.quiz.length; i++) {
      const q = s.quiz[i];
      if (!q.options || q.options.length !== 4) {
        console.error(`ERROR in ${s.id} Q${i + 1}: must have 4 options!`);
        hasErrors = true;
      }
      if (q.options[q.answerIndex] !== q.answer) {
        console.error(`ERROR in ${s.id} Q${i + 1}: answer mismatch! Index: ${q.answerIndex}, Option: "${q.options[q.answerIndex]}", Answer: "${q.answer}"`);
        hasErrors = true;
      }
    }
  }
  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`ERROR in ${s.id}: discussion_questions must have exactly 6 items!`);
    hasErrors = true;
  } else {
    const tiers = ['Remembering', 'Understanding', 'Applying', 'Analyzing', 'Evaluating', 'Creating'];
    for (let i = 0; i < 6; i++) {
      if (s.discussion_questions[i].tier !== tiers[i]) {
        console.error(`ERROR in ${s.id} DQ${i + 1}: expected tier ${tiers[i]}, got ${s.discussion_questions[i].tier}`);
        hasErrors = true;
      }
    }
  }
}

if (hasErrors) {
  process.exit(1);
}

console.log(`All ${batch.length} Mulla Nasruddin stories in Batch 14 passed self-validation!`);

