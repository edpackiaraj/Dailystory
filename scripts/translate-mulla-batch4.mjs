for (const item of batch) {
  for (const v of item.vocabulary) {
    if (!item.full_text.includes(v.word)) {
      console.error(`ERROR in ${item.id}: vocabulary word "${v.word}" NOT found in full_text!`);
      process.exit(1);
    }
  }
  console.log(`Verified vocabulary for ${item.id}: all 4 words match verbatim.`);
}

// Update stories
let updated = 0;
for (const item of batch) {
  const idx = stories.findIndex(s => s.id === item.id);
  if (idx !== -1) {
    stories[idx] = {
      ...stories[idx],
      language: "ta",
      title: item.title,
      summary: item.summary,
      moral: item.moral,
      full_text: item.full_text,
      word_count: item.full_text.split(/\s+/).filter(Boolean).length,
      reading_time: `${Math.ceil(item.full_text.split(/\s+/).filter(Boolean).length / 100)} mins`,
      listen_time: `${Math.ceil(item.full_text.split(/\s+/).filter(Boolean).length / 90)} mins`,
      vocabulary: item.vocabulary,
      quiz: item.quiz,
      discussion_questions: item.discussion_questions,
      reviewed: true
    };
    updated++;
  } else {
    console.error(`Story ID not found: ${item.id}`);
  }
}

