// Validation
let errors = 0;
for (const s of storiesData) {
  const words = s.full_text.trim().split(/\s+/).length;
  console.log(`Story ${s.id}: ${words} words`);
  if (words < 160 || words > 185) {
    console.error(`[ERR] Story ${s.id} words out of range (160-185): ${words}`);
    errors++;
  }
  const paras = s.full_text.trim().split(/\n\s*\n/);
  if (paras.length !== 3) {
    console.error(`[ERR] Story ${s.id} paras != 3: ${paras.length}`);
    errors++;
  }
  if (!s.vocabulary || s.vocabulary.length !== 4) {
    console.error(`[ERR] Story ${s.id} vocab length != 4`);
    errors++;
  } else {
    s.vocabulary.forEach((v, idx) => {
      if (!s.full_text.includes(v.word)) {
        console.error(`[ERR] Story ${s.id} vocab [${idx}] '${v.word}' not in full_text`);
        errors++;
      }
      if (!v.gloss || v.gloss.trim() === '') {
        console.error(`[ERR] Story ${s.id} vocab [${idx}] gloss empty`);
        errors++;
      }
    });
  }
  if (!s.quiz || s.quiz.length !== 3) {
    console.error(`[ERR] Story ${s.id} quiz length != 3`);
    errors++;
  }
  if (!s.discussion_questions || s.discussion_questions.length !== 6) {
    console.error(`[ERR] Story ${s.id} discussion_questions length != 6`);
    errors++;
  } else {
    s.discussion_questions.forEach((q, idx) => {
      if (q.tier !== bloomTiers[idx] || q.type !== bloomTiers[idx]) {
        console.error(`[ERR] Story ${s.id} bloom tier mismatch at [${idx}]`);
        errors++;
      }
    });
  }
}

if (errors > 0) {
  console.error(`\nValidation failed with ${errors} errors.`);
  process.exit(1);
}

console.log(`\nValidation passed for all ${storiesData.length} stories with 0 errors!\n`);

// Update allStories
let updatedCount = 0;
for (const s of storiesData) {
  const idx = allStories.findIndex(story => story.id === s.id);
  if (idx === -1) {
    console.error(`Story ID not found in stories-ta.json: ${s.id}`);
    process.exit(1);
  }
  const orig = allStories[idx];
  const words = s.full_text.trim().split(/\s+/).length;

  allStories[idx] = {
    ...orig,
    title: s.title,
    summary: s.summary,
    moral: s.moral,
    full_text: s.full_text,
    word_count: words,
    language: 'ta',
    vocabulary: s.vocabulary,
    quiz: s.quiz,
    discussion_questions: s.discussion_questions
  };
  console.log(`Updated story ${s.id} at index ${idx} (${words} words)`);
  updatedCount++;
}

